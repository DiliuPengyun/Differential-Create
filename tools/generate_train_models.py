"""Create-native textures and compact additions to the existing bogey meshes."""
import json
import math
from copy import deepcopy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / 'src/main/resources/assets/differentialcreate/models/block'

def save(path, data):
    for element in data.get('elements', []):
        assert all(-16 <= v <= 32 for key in ('from', 'to') for v in element[key]), path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def box(low, high, texture, uv=(0, 0, 16, 16), rotation=None):
    element = {'from': low, 'to': high,
        'faces': {side: {'uv': list(uv), 'texture': texture}
                  for side in ('north', 'south', 'east', 'west', 'up', 'down')}}
    if rotation:
        element['rotation'] = rotation
    return element

def bogey():
    # A flush engine cover on the original wood only. Native brass edging,
    # adhesive faces, lower casing, wheels and external linkages are untouched.
    # Reuse Create's steam-engine plate and linkage bolt pixels without tinting.
    cover = []

    def face(low, high, side, texture, uv):
        element = box(low, high, texture, uv)
        element['faces'] = {side: element['faces'][side]}
        cover.append(element)

    lid_y, detail_y = 16+1/64, 16+1/32
    face([2, lid_y, 2], [14, lid_y, 14], 'up', '#engine', (.5, 8.5, 7.5, 15.5))
    # The central inlet aligns with the existing hose's fixed top socket.
    face([7, detail_y, 7], [9, detail_y, 9], 'up', '#linkage', (11.5, 3.5, 12.5, 4.5))
    bolt_uv = (2, 2.5, 3, 3.5)
    for x in (3, 12):
        for z in (3, 12):
            face([x, detail_y, z], [x+1, detail_y, z+1], 'up', '#linkage', bolt_uv)
    for side in ('east', 'west'):
        x = 16 if side == 'east' else 0
        face([x, 12, 2], [x, 16, 14], side, '#engine', (.5, 8.5, 7.5, 10.5))
        screw_x = x + (1/64 if side == 'east' else -1/64)
        for z in (3, 12):
            face([screw_x, 14, z], [screw_x, 15, z+1], side, '#linkage', bolt_uv)
    save(MODELS / 'steam_bogey/engine_cover.json', {'parent': 'minecraft:block/block',
         'render_type': 'minecraft:cutout_mipped', 'ambientocclusion': False,
         'textures': {'engine': 'create:block/engine', 'linkage': 'create:block/cam_linkage',
                      'particle': 'create:block/copper_underside'},
         'elements': cover})
    # The condenser changes only the existing flush panel's texture.
    # Keep the original brass, inlet, screws and complete native bogey mesh.
    # Reuse the engine atlas layout and UVs, so its 14x14 top and 14x4 side
    # texels have exactly the same density as the uncooled engine cover.
    cooled = deepcopy(cover)
    save(MODELS / 'steam_bogey/condenser_cover.json', {'parent': 'minecraft:block/block',
         'render_type': 'minecraft:cutout_mipped', 'ambientocclusion': False,
         'textures': {'engine': 'differentialcreate:block/steam_bogey/condenser_panel',
                      'linkage': 'create:block/cam_linkage',
                      'particle': 'differentialcreate:block/steam_bogey/condenser_panel'},
         'elements': cooled})

def levers():
    # Bake the rigid handle into a mesh so all forward detents can be on one
    # side of centred neutral. The built-in OBJ loader handles world, item and
    # contraption rendering; the original casing and lever UVs are retained.
    material_path = MODELS / 'gear_lever.mtl'
    material_path.write_text('\n\n'.join(
        f'newmtl {name}\nKd 1 1 1\nKa 0 0 0\nmap_Kd {texture}'
        for name, texture in (('side', 'create:block/railway_casing_side'),
                              ('end', 'create:block/railway_casing'),
                              ('handle', 'minecraft:block/lever'))) + '\n', encoding='utf-8')
    for gear, angle in ((6, -45), (0, 0), (1, 9), (2, 18), (3, 27), (4, 36), (5, 45)):
        base = box([4, 0, 3], [12, 3, 13], '#side')
        base['faces']['up']['texture'] = '#end'
        base['faces']['down']['texture'] = '#end'
        handle = box([7, 3, 7], [9, 13, 9], '#handle', (7, 6, 9, 16),
                     {'origin': [8, 3, 8], 'axis': 'x', 'angle': angle})
        for side in ('up', 'down'):
            handle['faces'][side]['uv'] = [7, 6, 9, 8]
        mesh = ['# Generated by generate_train_models.py; positions are in block units.',
                'mtllib gear_lever.mtl']
        index = 1
        for element in (base, handle):
            mesh.append('g casing' if element is base else 'g handle')
            x0, y0, z0 = element['from']
            x1, y1, z1 = element['to']
            faces = {
                'down': ((x0, y0, z1), (x0, y0, z0), (x1, y0, z0), (x1, y0, z1)),
                'up': ((x0, y1, z0), (x0, y1, z1), (x1, y1, z1), (x1, y1, z0)),
                'north': ((x1, y1, z0), (x1, y0, z0), (x0, y0, z0), (x0, y1, z0)),
                'south': ((x0, y1, z1), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1)),
                'west': ((x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1)),
                'east': ((x1, y1, z1), (x1, y0, z1), (x1, y0, z0), (x1, y1, z0)),
            }
            for side, points in faces.items():
                face = element['faces'][side]
                mesh.append('usemtl ' + face['texture'].removeprefix('#'))
                for x, y, z in points:
                    if 'rotation' in element:
                        rotation = element['rotation']
                        _, oy, oz = rotation['origin']
                        c, s = math.cos(math.radians(angle)), math.sin(math.radians(angle))
                        y, z = oy + c * (y-oy) - s * (z-oz), oz + s * (y-oy) + c * (z-oz)
                    mesh.append(f'v {x/16:.9f} {y/16:.9f} {z/16:.9f}')
                u0, v0, u1, v1 = face['uv']
                mesh.extend(f'vt {u/16:.9f} {v/16:.9f}' for u, v in ((u0, v0), (u0, v1), (u1, v1), (u1, v0)))
                mesh.append('f ' + ' '.join(f'{i}/{i}' for i in range(index, index+4)))
                index += 4
        (MODELS / f'gear_lever_{gear}.obj').write_text('\n'.join(mesh) + '\n', encoding='utf-8')
        save(MODELS / f'gear_lever_{gear}.json', {'parent': 'minecraft:block/block',
            'loader': 'neoforge:obj', 'model': f'differentialcreate:models/block/gear_lever_{gear}.obj',
            'automatic_culling': False, 'shade_quads': True, 'flip_v': False, 'emissive_ambient': False,
            'textures': {'side': 'create:block/railway_casing_side', 'end': 'create:block/railway_casing',
                         'handle': 'minecraft:block/lever', 'particle': 'create:block/railway_casing_side'},
            })
    save(MODELS.parents[1] / 'blockstates/gear_lever.json', {'variants': {
        f'gear={gear}': {'model': f'differentialcreate:block/gear_lever_{gear}'} for gear in range(7)}})

def item_sprites():
    # Standard flat inventory/held-item sprites; no hand-built cuboid meshes.
    for name in ('steam_hose', 'condenser_pipe'):
        save(MODELS.parent / f'item/{name}.json', {'parent': 'minecraft:item/generated',
             'textures': {'layer0': f'differentialcreate:item/{name}'}})

if __name__ == '__main__':
    bogey()
    levers()
    item_sprites()
